def build_data() -> None:
    wb = Workbook()
    style_data_sheet(new_sheet(wb, "岗位", [POSITION_HEADER, *POSITION_ROWS], first=True))
    wb.save(ROOT / "岗位清单.xlsx")

    wb = Workbook()
    style_data_sheet(new_sheet(wb, "关键岗位", [KEY_HEADER, *KEY_ROWS], first=True))
    wb.save(ROOT / "关键岗位清单.xlsx")


