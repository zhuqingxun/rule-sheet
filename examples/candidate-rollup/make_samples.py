"""生成「候选人汇总」样例: 三份数据 + Excel 决策表, 全部写到本脚本所在目录。

业务: 岗位清单里每个岗位要填「拟任人」几列, 而推荐记录是一岗多人 (一人一行); 现任者的冻结记录也是一人多条。
0.7 的「重复键: 拼接」把参照表里同一个键的多行按排序接成一行, 规则层仍然逐行: 输出格直接复制 `推荐.工号` 就是 `E2;E1;E3`。

这个样例展示:
    - 「设置」里输入表的 重复键 = 拼接, 以及只在这时有意义的四个可选列: 排序 / 分隔符 / 空值占位 / 带序号
    - 排序: `推荐时间 降序`, 空值一律排末尾; 空值占位 NA 让各列按位置对齐 (第 k 个工号对应第 k 个姓名)
    - 带序号: 冻结记录接成 `1.…;2.…`
    - 带输入前缀的派生变量 (变量定义里的 `推荐.现岗` / `冻结.期间`): 在那张表自己的行上逐行算, 发生在聚合之前;
      拼接() 的列参数全空时为空 (再被占位成 NA), 部分空出 `-经理-23级`
    - 测试用例里聚合后的变量直接给拼好的文本, 带前缀的派生变量也直接给值 (不推导)

运行:
    uv run python examples/candidate-rollup/make_samples.py

产物:
    岗位清单.xlsx      被更新的主表 (规则里叫 岗位); 拟任人 / 冻结 几列是留空的新增列
    推荐记录.xlsx      参照表 (规则里叫 推荐), 一岗多行
    冻结记录.xlsx      参照表 (规则里叫 冻结), 按 工号 = 岗位.现任工号 对齐, 一人多行
    规则_决策表.xlsx   四张 sheet: 设置 (只有输入表, 没有设置项) / 变量定义 / 决策表 / 测试
"""
from __future__ import annotations

from collections.abc import Iterable
from datetime import datetime
from pathlib import Path
from typing import Any

from openpyxl import Workbook
from openpyxl.worksheet.worksheet import Worksheet

from rule_sheet.style import INPUTS_TITLE, style_data_sheet, style_rules_workbook

ROOT = Path(__file__).resolve().parent


def new_sheet(wb: Workbook, title: str, rows: Iterable[Iterable[Any]], *, first: bool = False) -> Worksheet:
    ws = wb.active if first else wb.create_sheet()
    ws.title = title
    for row in rows:
        ws.append(list(row))
    return ws


def d(text: str) -> datetime:
    return datetime.strptime(text, "%Y-%m-%d")


# ---------------------------------------------------------------------------
# 样例数据: 每个岗位对应一种情形
# ---------------------------------------------------------------------------
POSITION_HEADER = ["岗位编码", "岗位名称", "现任工号", "拟任人工号", "拟任人姓名", "拟任人现岗", "推荐时间", "冻结期间", "冻结依据"]
POSITION_ROWS = [
    # 编码   名称            现任   (后六列留空, 由规则填)                       推荐记录 / 冻结记录                       预期
    ["P1", "财务部-部长",   "C1", None, None, None, None, None, None],  # 三条推荐 (一条无推荐时间, 一条无部门); 两条冻结  -> 按推荐时间降序, 空值排末尾并占位 NA
    ["P2", "市场部-经理",   "C2", None, None, None, None, None, None],  # 两条推荐都没有推荐时间; 无冻结                -> 推荐时间 NA;NA, 顺序按原文件
    ["P3", "法务部-主管",   "C3", None, None, None, None, None, None],  # 无推荐; 一条冻结 (结束日期为空)                -> 只命中 F1, 期间 1.2026-08-10~
    ["P4", "研发中心-主任", None, None, None, None, None, None, None],  # 两条推荐 (一条部门/岗位/职级全空); 现任工号为空  -> 现岗 NA;…, 冻结匹配不到
]

RECOMMEND_HEADER = ["岗位编码", "工号", "姓名", "现部门", "现岗位", "职级", "推荐时间"]
RECOMMEND_ROWS = [
    ["P1", "E1", "张三", "财务部", "会计",   "22级", d("2026-09-01")],
    ["P1", "E2", "李四", None,    "经理",   "23级", d("2026-10-01")],  # 现部门为空 -> 现岗 -经理-23级
    ["P1", "E3", "王五", "人事部", "主管",   "21级", None],            # 推荐时间为空 -> 排末尾, 占位 NA
    ["P2", "E4", "赵六", "市场部", "经理",   None,   None],
    ["P2", "E7", "孙九", "销售部", "主管",   "22级", None],
    ["P4", "E5", "周七", None,    None,     None,   d("2026-07-01")],  # 三列全空 -> 现岗 为空 -> 占位 NA
    ["P4", "E6", "吴八", "研发部", "工程师", "20级", d("2026-06-01")],
]

FREEZE_HEADER = ["工号", "冻结开始", "冻结结束", "冻结依据"]
FREEZE_ROWS = [
    ["C1", d("2026-09-01"), d("2026-09-30"), "审计"],
    ["C1", d("2026-05-01"), d("2026-05-31"), "纪律"],
    ["C3", d("2026-08-10"), None,            "休假"],  # 结束为空 -> 期间 2026-08-10~
]


def build_data() -> None:
    for name, header, rows in (
        ("岗位清单", POSITION_HEADER, POSITION_ROWS),
        ("推荐记录", RECOMMEND_HEADER, RECOMMEND_ROWS),
        ("冻结记录", FREEZE_HEADER, FREEZE_ROWS),
    ):
        wb = Workbook()
        style_data_sheet(new_sheet(wb, name, [header, *rows], first=True))
        wb.save(ROOT / f"{name}.xlsx")


# ---------------------------------------------------------------------------
# 规则工作簿
# ---------------------------------------------------------------------------
def build_rules() -> None:
    wb = Workbook()

    # ---- sheet 1: 设置 (没有设置项, 只有输入表; 重复键 = 拼接 的参照表多四个可选列) ------------------
    new_sheet(wb, "设置", [
        INPUTS_TITLE,
        ("名称", "匹配", "重复键", "排序", "分隔符", "空值占位", "带序号", "文件", "说明"),
        ("岗位", "主表", None, None, None, None, None, "岗位清单.xlsx",
         "被更新的表: 输出的行就是它的行"),
        ("推荐", "岗位编码", "拼接", "推荐时间 降序", None, "NA", None, "推荐记录.xlsx",
         "一岗多行: 同一个岗位的推荐记录按 推荐时间 降序 (空值排末尾) 接成一行, 每列各自接; 分隔符留空 = ;。空值占位 NA 让各列按位置对齐 (第 k 个工号对应第 k 个姓名)"),
        ("冻结", "工号 = 岗位.现任工号", "拼接", "冻结开始 降序", None, None, "是", "冻结记录.xlsx",
         "按 工号 对齐到主表的 现任工号; 带序号 = 1.…;2.…。排序 / 分隔符 / 空值占位 / 带序号 只在 重复键 = 拼接 时允许写"),
    ], first=True)

    # ---- sheet 2: 变量定义 (带输入前缀的派生变量在那张表自己的行上算, 发生在聚合之前) ----
    new_sheet(wb, "变量定义", [
        ("变量", "定义", "说明"),
        ("推荐.现岗", '拼接(推荐.现部门, "-", 推荐.现岗位, "-", 推荐.职级)',
         "名字带 推荐. 前缀 = 在推荐记录的每一行上算, 然后才聚合; 只能引用推荐记录自己的列。三列全空为空 (再被占位成 NA), 部分空出 -经理-23级"),
        ("冻结.期间", '拼接(冻结.冻结开始, "~", 冻结.冻结结束)',
         "同上。聚合后是 1.2026-09-01~2026-09-30;2.…。测试用例里这两个变量直接给拼好的文本, 不推导"),
        (None, None, None),
        ("可用函数", None,
         "abs  round  天数差(晚, 早)  非空(x)  为空(x)  属于(x, 值1, ...)  "
         "包含 / 不包含 / 开头是 / 开头不是 / 结尾是 / 结尾不是 (x, 文本1, ...)  拼接(a, b, ...)  数字(x)  日期(x)  如果(条件, 真值, 假值)"),
    ])

    # ---- sheet 3: 决策表 ------------------------------------------------------
    kinds = ["规则ID", "优先级", "输入", "输入", "输出", "输出", "输出", "输出", "输出", "输出", "说明"]
    names = ["规则ID", "优先级", "推荐.存在", "冻结.存在", "拟任人工号", "拟任人姓名", "拟任人现岗", "推荐时间", "冻结期间", "冻结依据", "说明"]
    rules = [
        ["P1", 1, "是", "-", "推荐.工号", "推荐.姓名", "推荐.现岗", "推荐.推荐时间", "-", "-",
         "有推荐记录的岗位: 四列都是聚合后的文本 (E2;E1;E3), 输出格直接复制"],
        ["F1", 2, "-", "是", "-", "-", "-", "-", "冻结.期间", "冻结.冻结依据",
         "现任者有冻结记录: 带序号 1.…;2.…"],
    ]
    new_sheet(wb, "决策表", [
        ["命中策略", "优先级", "两条规则各管各的列, 同时命中互不干扰。聚合发生在匹配层 (输入声明), 规则层仍是逐行"],
        kinds, names, *rules,
    ])

    # ---- sheet 4: 测试 (聚合后的变量直接给拼好的文本) ------------------------------
    kinds = ["用例", *["输入"] * 8, *["期望"] * 6, "说明"]
    names = ["用例", "推荐.存在", "推荐.工号", "推荐.姓名", "推荐.现岗", "推荐.推荐时间", "冻结.存在", "冻结.期间", "冻结.冻结依据",
             "拟任人工号", "拟任人姓名", "拟任人现岗", "推荐时间", "冻结期间", "冻结依据", "说明"]
    tests = [
        ["T1", "是", "E2;E1;E3", "李四;张三;王五", "-经理-23级;财务部-会计-22级;人事部-主管-21级", "2026-10-01;2026-09-01;NA", "否", None, None,
         "E2;E1;E3", "李四;张三;王五", "-经理-23级;财务部-会计-22级;人事部-主管-21级", "2026-10-01;2026-09-01;NA", None, None,
         "用例里 推荐.工号 等直接写聚合后的文本; 推荐.现岗 是带前缀的派生变量, 也直接给值"],
        ["T2", "否", None, None, None, None, "否", None, None,
         None, None, None, None, None, None,
         "都没有记录, 不动"],
        ["T3", "否", None, None, None, None, "是", "1.2026-09-01~2026-09-30;2.2026-05-01~2026-05-31", "1.审计;2.纪律",
         None, None, None, None, "1.2026-09-01~2026-09-30;2.2026-05-01~2026-05-31", "1.审计;2.纪律",
         "只有冻结记录"],
        ["T4", "是", "E5;E6", "周七;吴八", "NA;研发部-工程师-20级", "2026-07-01;2026-06-01", "是", "1.2026-08-10~", "1.休假",
         "E5;E6", "周七;吴八", "NA;研发部-工程师-20级", "2026-07-01;2026-06-01", "1.2026-08-10~", "1.休假",
         "两条都命中, 各写各的列"],
    ]
    new_sheet(wb, "测试", [kinds, names, *tests])

    style_rules_workbook(wb)
    wb.save(ROOT / "规则_决策表.xlsx")


if __name__ == "__main__":
    build_data()
    build_rules()
    print(f"已生成到 {ROOT}: 岗位清单.xlsx  推荐记录.xlsx  冻结记录.xlsx  规则_决策表.xlsx")
