"""生成「两期比对」样例: 两份数据 + Excel 决策表, 全部写到本脚本所在目录。

业务: 每期一张全量岗位表, 要给业务人员一份「这期比上期哪些岗位新增 / 变了 / 没变 / 没了, 变了的是哪些字段、从什么变成什么」。
输出是本期的副本: 每行写 差异类型 (ADDED / CHANGED / UNCHANGED / REMOVED) 和 变更字段明细 (`岗位职级:21级->22级;绩效:A->B`),
上期有本期没有的岗位追加在末尾标 REMOVED。

这个样例展示 0.7 加的两件事:
    - 差异(本期, 上期, 对比字段): 字段组里的每一列逐个比两期的同名列, 变化的拼成 字段:旧值->新值, 多个用 ; 接, 没变化为空。
      相等判定与审计列同一套 (空串与空值相同, 文本严格); 空值显示为空串 (拟任人:李四->)
    - 「输入」里 独有行 = 追加: 上期里本期没有的岗位接到输出末尾, 同名列带入; 主表 本期.存在 在这些行上是 否
    - 首次命中 下四条规则按顺序: 没了 / 新增 / 变了 / 没变

运行:
    uv run python examples/period-diff/make_samples.py

产物:
    本期全量.xlsx      被更新的主表 (规则里叫 本期); 差异类型 / 变更字段明细 是留空的新增列
    上期全量.xlsx      参照表 (规则里叫 上期), 独有行 追加
    规则_决策表.xlsx   五张 sheet: 设置 (含输入表) / 变量定义 / 字段组 / 决策表 / 测试
"""
from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path
from typing import Any

from openpyxl import Workbook
from openpyxl.worksheet.worksheet import Worksheet

from rule_sheet.style import INPUTS_TITLE, SETTINGS_TITLE, style_data_sheet, style_rules_workbook

ROOT = Path(__file__).resolve().parent


def new_sheet(wb: Workbook, title: str, rows: Iterable[Iterable[Any]], *, first: bool = False) -> Worksheet:
    ws = wb.active if first else wb.create_sheet()
    ws.title = title
    for row in rows:
        ws.append(list(row))
    return ws


# ---------------------------------------------------------------------------
# 样例数据: 每个岗位对应一种差异情形
# ---------------------------------------------------------------------------
CURRENT_HEADER = ["岗位编码", "岗位名称", "岗位职级", "一层组织", "拟任人", "绩效", "差异类型", "变更字段明细"]
CURRENT_ROWS = [
    # 编码   名称          职级    一层组织    拟任人  绩效   (后两列留空, 由规则填)   上期情况                    预期
    ["Q1", "财务部-部长", "22级", "1-集团",   "张三", "B",  None, None],  # 职级 21级, 绩效 A           -> CHANGED 岗位职级:21级->22级;绩效:A->B
    ["Q2", "人事部-部长", "20级", "1-集团",   None,   None, None, None],  # 拟任人 李四, 本期为空        -> CHANGED 拟任人:李四-> (空值显示为空串)
    ["Q3", "市场部-经理", "19级", "2-终端",   "王五", "C",  None, None],  # 上期没有                    -> ADDED
    ["Q4", "法务部-主管", "18级", "1-集团",   "赵六", "B",  None, None],  # 完全相同                    -> UNCHANGED
    ["Q5", "研发-主任",   "23级", "3-研发",   None,   "A",  None, None],  # 一层组织 3-研发体系          -> CHANGED 一层组织:3-研发体系->3-研发
]

PREVIOUS_HEADER = ["岗位编码", "岗位名称", "岗位职级", "一层组织", "拟任人", "绩效"]
PREVIOUS_ROWS = [
    ["Q1", "财务部-部长", "21级", "1-集团",     "张三", "A"],
    ["Q2", "人事部-部长", "20级", "1-集团",     "李四", None],
    ["Q4", "法务部-主管", "18级", "1-集团",     "赵六", "B"],
    ["Q5", "研发-主任",   "23级", "3-研发体系", None,   "A"],
    ["Q6", "采购部-经理", "20级", "4-供应链",   "周七", "B"],  # 本期没有 -> 追加到末尾, REMOVED, 五列带入
]


def build_data() -> None:
    wb = Workbook()
    style_data_sheet(new_sheet(wb, "本期全量", [CURRENT_HEADER, *CURRENT_ROWS], first=True))
    wb.save(ROOT / "本期全量.xlsx")
    wb = Workbook()
    style_data_sheet(new_sheet(wb, "上期全量", [PREVIOUS_HEADER, *PREVIOUS_ROWS], first=True))
    wb.save(ROOT / "上期全量.xlsx")


# ---------------------------------------------------------------------------
# 规则工作簿
# ---------------------------------------------------------------------------
def build_rules() -> None:
    wb = Workbook()

    # ---- sheet 1: 设置 (上方设置项; 空一行; 下方输入表, 上期 独有行 = 追加) --------------
    new_sheet(wb, "设置", [
        SETTINGS_TITLE,
        ("输出", "output/本期全量_更新后.xlsx", "默认输出路径, 相对本规则文件所在目录, 命令行 -o 可覆盖"),
        (None, None, None),
        INPUTS_TITLE,
        ("名称", "匹配", "重复键", "独有行", "文件", "说明"),
        ("本期", "主表", None, None, "本期全量.xlsx", "被更新的表: 输出的行就是它的行 (加上下面追加的)。本期.存在 在追加来的行上是 否"),
        ("上期", "岗位编码", None, "追加", "上期全量.xlsx",
         "按 岗位编码 对齐; 独有行 = 追加: 上期有本期没有的岗位接到输出末尾, 同名列 (岗位名称 … 绩效) 带入, 本期独有的列为空"),
    ], first=True)

    # ---- sheet 2: 变量定义 ----------------------------------------------------
    new_sheet(wb, "变量定义", [
        ("变量", "定义", "说明"),
        ("变更明细", "差异(本期, 上期, 对比字段)",
         "字段组 对比字段 里的每一列逐个比两期的同名列, 变化的拼成 字段:旧值->新值, 多个用 ; 接, 没有变化为空。"
         "相等判定与审计列同一套 (空串与空值相同, 文本严格比较); 空值显示为空串。第四个参数可改分隔符: 差异(本期, 上期, 对比字段, 分隔符=\"|\")"),
        (None, None, None),
        ("可用函数", None,
         "abs  round  天数差(晚, 早)  非空(x)  为空(x)  属于(x, 值1, ...)  "
         "包含 / 不包含 / 开头是 / 开头不是 / 结尾是 / 结尾不是 (x, 文本1, ...)  拼接(a, b, ...)  数字(x)  日期(x)  如果(条件, 真值, 假值)  差异(新, 旧, 字段组)"),
    ])

    # ---- sheet 3: 字段组 -------------------------------------------------------
    new_sheet(wb, "字段组", [
        ("名称", "列名", "说明"),
        ("对比字段", "岗位名称, 岗位职级, 一层组织, 拟任人, 绩效", "两期要逐个比的列, 写一次; 改清单不碰表达式"),
    ])

    # ---- sheet 4: 决策表 -------------------------------------------------------
    kinds = ["规则ID", "优先级", "输入", "输入", "输入", "输出", "输出", "说明"]
    names = ["规则ID", "优先级", "本期.存在", "上期.存在", "变更明细", "差异类型", "变更字段明细", "说明"]
    rules = [
        ["D1", 1, "否", "-", "-",     "REMOVED",   "清空",     "追加来的行 (上期有本期没有): 本期.存在 是 否"],
        ["D2", 2, "-", "否", "-",     "ADDED",     "清空",     "上期没有这个岗位"],
        ["D3", 3, "-", "-", "!= 空",  "CHANGED",   "变更明细", "有字段变了: 把 差异() 算出来的明细写进去"],
        ["D4", 4, "-", "-", "-",      "UNCHANGED", "清空",     "兜底: 两期都有且没变。变更字段明细 每次重算, 所以 D1 / D2 / D4 都显式清空"],
    ]
    new_sheet(wb, "决策表", [
        ["命中策略", "首次命中", "四种差异互斥, 按顺序: 没了 / 新增 / 变了 / 没变"],
        kinds, names, *rules,
    ])

    # ---- sheet 5: 测试 ---------------------------------------------------------
    kinds = ["用例", *["输入"] * 10, *["期望"] * 2, "说明"]
    names = ["用例", "本期.存在", "上期.存在", "本期.岗位名称", "上期.岗位名称", "本期.岗位职级", "上期.岗位职级",
             "本期.拟任人", "上期.拟任人", "本期.绩效", "上期.绩效", "差异类型", "变更字段明细", "说明"]
    tests = [
        ["T1", "是", "是", "财务部-部长", "财务部-部长", "22级", "21级", "张三", "张三", "B", "A", "CHANGED", "岗位职级:21级->22级;绩效:A->B", "两列变了, 按字段组顺序拼"],
        ["T2", "是", "否", "市场部-经理", None, "19级", None, "王五", None, "C", None, "ADDED", "空", "上期没有; 变更字段明细 显式清空 (期望格写 空)"],
        ["T3", "是", "是", "法务部-主管", "法务部-主管", "18级", "18级", "赵六", "赵六", "B", "B", "UNCHANGED", "空", "完全相同"],
        ["T4", "否", "是", None, "采购部-经理", None, "20级", None, "周七", None, "B", "REMOVED", "空", "追加来的行: 本期.存在 写 否 (没写默认是 是)"],
        ["T5", "是", "是", "人事部-部长", "人事部-部长", "20级", "20级", None, "李四", None, None, "CHANGED", "拟任人:李四->", "新值为空显示为空串"],
        ["T6", "是", "是", "人事部-部长", "人事部-部长", "20级", "20级", "王五", None, None, None, "CHANGED", "拟任人:->王五", "旧值为空显示为空串"],
    ]
    new_sheet(wb, "测试", [kinds, names, *tests])

    style_rules_workbook(wb)
    wb.save(ROOT / "规则_决策表.xlsx")


if __name__ == "__main__":
    build_data()
    build_rules()
    print(f"已生成到 {ROOT}: 本期全量.xlsx  上期全量.xlsx  规则_决策表.xlsx")
